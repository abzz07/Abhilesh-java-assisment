public class StudentGrade {
    public static void main(String[] args) {
        int marks = 95;

        if (marks > 90) {
            System.out.println("Grade: A");
        }

        if (marks >= 70) {
            System.out.println("Result: Passed");
        } else {
            System.out.println("Result: Failed");
        }
    }
}
